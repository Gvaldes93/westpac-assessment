package com.sourcecodesolutions.techassesment.westpac.account;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.headers.Header;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import java.net.URI;
import java.util.UUID;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ProblemDetail;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.servlet.support.ServletUriComponentsBuilder;

// TODO: secure with OAuth2 resource server and derive the customer from the token rather than the body.
// TODO: support an Idempotency-Key header on POST so client retries cannot open duplicate accounts.
@Tag(name = AccountApiDocs.TAG, description = "Savings bank accounts")
@RestController
@RequestMapping(AccountController.BASE_PATH)
class AccountController {

    static final String BASE_PATH = "/api/v1/accounts";
    private static final String ID_PATH = "/{id}";

    private final AccountService accountService;

    AccountController(AccountService accountService) {
        this.accountService = accountService;
    }

    @Operation(
            summary = "Open a savings account",
            description = "Id and account number are generated by the API. A customer may hold at most 5 accounts.")
    @ApiResponse(responseCode = AccountApiDocs.CREATED, description = "Account created",
            headers = @Header(name = HttpHeaders.LOCATION, description = "URL of the new account"),
            content = @Content(mediaType = MediaType.APPLICATION_JSON_VALUE,
                    schema = @Schema(implementation = AccountResponse.class)))
    @ApiResponse(responseCode = AccountApiDocs.BAD_REQUEST,
            description = "Validation failed; per-field messages are listed under `errors`",
            content = @Content(mediaType = AccountApiDocs.PROBLEM_JSON, schema = @Schema(implementation = ProblemDetail.class)))
    @ApiResponse(responseCode = AccountApiDocs.UNPROCESSABLE_CONTENT,
            description = "Customer already holds the maximum number of accounts",
            content = @Content(mediaType = AccountApiDocs.PROBLEM_JSON, schema = @Schema(implementation = ProblemDetail.class)))
    @ApiResponse(responseCode = AccountApiDocs.SERVICE_UNAVAILABLE,
            description = "Database unavailable; retry after the `Retry-After` delay",
            content = @Content(mediaType = AccountApiDocs.PROBLEM_JSON, schema = @Schema(implementation = ProblemDetail.class)))
    @PostMapping
    ResponseEntity<AccountResponse> createAccount(@Valid @RequestBody CreateAccountRequest request) {
        AccountResponse created = accountService.createAccount(request);
        URI location = ServletUriComponentsBuilder.fromCurrentRequest()
                .path(ID_PATH)
                .buildAndExpand(created.id())
                .toUri();
        return ResponseEntity.created(location).body(created);
    }

    @Operation(summary = "Get a savings account")
    @ApiResponse(responseCode = AccountApiDocs.OK, description = "Account found",
            content = @Content(mediaType = MediaType.APPLICATION_JSON_VALUE,
                    schema = @Schema(implementation = AccountResponse.class)))
    @ApiResponse(responseCode = AccountApiDocs.BAD_REQUEST, description = "Id is not a valid UUID",
            content = @Content(mediaType = AccountApiDocs.PROBLEM_JSON, schema = @Schema(implementation = ProblemDetail.class)))
    @ApiResponse(responseCode = AccountApiDocs.NOT_FOUND, description = "Account not found",
            content = @Content(mediaType = AccountApiDocs.PROBLEM_JSON, schema = @Schema(implementation = ProblemDetail.class)))
    @ApiResponse(responseCode = AccountApiDocs.SERVICE_UNAVAILABLE,
            description = "Account not cached and database unavailable; retry after the `Retry-After` delay",
            content = @Content(mediaType = AccountApiDocs.PROBLEM_JSON, schema = @Schema(implementation = ProblemDetail.class)))
    @GetMapping(ID_PATH)
    AccountResponse getAccount(@Parameter(description = "Account id") @PathVariable UUID id) {
        return accountService.getAccount(id);
    }
}
